import pandas as pd
import numpy as np
import os
import json
from sklearn.metrics import precision_score, recall_score, f1_score, confusion_matrix

# Configuration #
OUTPUT_PATH = '../outputs/'
os.makedirs(OUTPUT_PATH, exist_ok=True)

# Load Data #
def load_featured_data():
    print("Loading feature-engineered data...")
    file_path = os.path.join(OUTPUT_PATH, "feature_engineered_data.csv")
    if not os.path.exists(file_path):
        raise FileNotFoundError(f"Error: The file {file_path} was not found. Please run the feature engineering script first.")
    
    # Load specific columns to save memory if needed, but for now load all
    df = pd.read_csv(file_path, parse_dates=["timestamp", "account_open_date"])
    print("Data loaded successfully.")
    return df

# Data Splitting #
def temporal_split(df, train_ratio=0.8):
    print(f"Performing temporal split with {train_ratio*100}% training data...")
    df_sorted = df.sort_values(by='timestamp')
    split_point = int(len(df_sorted) * train_ratio)
    
    df_train = df_sorted.iloc[:split_point]
    df_test = df_sorted.iloc[split_point:]
    
    print(f"Training set size: {len(df_train)}")
    print(f"Test set size: {len(df_test)}")
    return df_train, df_test

# Hard-Rule Implementation
def apply_hard_rules(df):
    
    print("Applying hard-coded AML rules...")
    
    # Initialize alerts series
    alerts = pd.Series(False, index=df.index)
    
    # Rule 1: Simple Monetary Threshold
    rule1 = df['amount'] > 10000
    
    # Rule 2: Structuring / Smurfing
    rule2 = (df['cust_txn_count_24h'] >= 3) & (df['cust_txn_sum_24h'] > 9000) & (df['amount'] < 10000)
    
    # Rule 3: High-Risk Jurisdiction
    rule3 = df['is_high_risk_country_receiver'] == 1
    
    # Rule 4: High Velocity / Rapid Movement
    rule4 = df['cust_txn_count_24h'] > 10
    
    # Rule 5: Profile Inconsistency
    # Flag if a transaction amount is unusually large compared to the customer's known income.
    # We use a threshold of 50% of annual income in a single transaction.
    rule5 = df['amount'] > (df['annual_income'] * 0.5)
    
    # Rule 6: Round Value Transactions
    # Flag large, round-value transactions that are often not typical for commercial activity.
    rule6 = (df['is_round_value'] == True) & (df['amount'] > 5000)
    
    # Rule 7: Dormant Account Activation
    # Flag a large transaction from an account that has been inactive.
    # We define 'dormant' as no transaction for 90 days (in seconds).
    ninety_days_in_seconds = 90 * 24 * 60 * 60
    rule7 = (df['time_since_last_txn_sec'] > ninety_days_in_seconds) & (df['amount'] > 5000)
    
    # Rule 8: Watchlist Hit
    # Flag any transaction where the customer is on a watchlist (PEP or Sanctioned).
    rule8 = df['is_on_watchlist'] == 1
    
    # Combine all rules with a logical OR. An alert is triggered if ANY rule is met.
    all_alerts = rule1 | rule2 | rule3 | rule4 | rule5 | rule6 | rule7 | rule8
    
    print(f"Total alerts generated by enhanced rules: {all_alerts.sum()}")
    return all_alerts.astype(int)

# Evaluation 
def evaluate_model(y_true, y_pred, model_name):
    print(f"\n Evaluating {model_name} ")
    
    # Fill NaN values in true labels if any, assuming NaN should be 0 (not suspicious)
    y_true = y_true.fillna(0)
    
    # Calculate metrics
    precision = precision_score(y_true, y_pred, zero_division=0)
    recall = recall_score(y_true, y_pred, zero_division=0)
    f1 = f1_score(y_true, y_pred, zero_division=0)
    
    # Confusion Matrix to calculate False Positive Rate (FPR)
    if len(y_true) != len(y_pred):
        print("Error: True labels and predictions have different lengths.")
        return {}
        
    tn, fp, fn, tp = confusion_matrix(y_true, y_pred, labels=[0, 1]).ravel()
    fpr = fp / (fp + tn) if (fp + tn) > 0 else 0
    
    print(f"Precision: {precision:.4f}")
    print(f"Recall (Sensitivity): {recall:.4f}")
    print(f"F1-Score: {f1:.4f}")
    print(f"False Positive Rate (FPR): {fpr:.4f}")
    print(f"True Positives: {tp}, False Positives: {fp}, True Negatives: {tn}, False Negatives: {fn}")
    
    metrics = {
        "model_name": model_name,
        "precision": precision,
        "recall": recall,
        "f1_score": f1,
        "false_positive_rate": fpr,
        "true_positives": int(tp),
        "false_positives": int(fp),
        "true_negatives": int(tn),
        "false_negatives": int(fn)
    }
    
    # Save metrics to a JSON file
    metrics_file = os.path.join(OUTPUT_PATH, f"{model_name.lower().replace(' ', '_')}_metrics.json")
    with open(metrics_file, 'w') as f:
        json.dump(metrics, f, indent=4)
    print(f"Metrics saved to {metrics_file}")
    
    return metrics

# Main Function
def main():
    df = load_featured_data()
    
    # Split data into train and test sets
    df_train, df_test = temporal_split(df)
    
    # We only apply the rules to the test set for evaluation
    test_predictions = apply_hard_rules(df_test)
    
    # Get true labels from the test set
    test_true_labels = df_test['is_suspicious']
    
    # Evaluate the performance
    evaluate_model(test_true_labels, test_predictions, "Hard-Rule Baseline ")
    
    # Save the test set with predictions for later analysis
    df_test_with_preds = df_test.copy()
    df_test_with_preds['hard_rule_alert'] = test_predictions
    output_file = os.path.join(OUTPUT_PATH, "test_set_with_rule_predictions.csv")
    df_test_with_preds.to_csv(output_file, index=False)
    print(f"\nTest set with rule predictions saved to: {output_file}")
    
    print("\n Hard-Rule Baseline Script Finished ")

if __name__ == "__main__":
    main()
